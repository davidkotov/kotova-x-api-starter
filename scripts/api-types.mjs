#!/usr/bin/env node
// Generates the TypeScript types of the Kotova X API from the vendored OpenAPI
// document.
//
//   pnpm gen:api     openapi/openapi.v1.json -> src/lib/kx/api-types.ts
//   pnpm check:api   regenerates into a temporary file and exits with 1 when the
//                    result differs from src/lib/kx/api-types.ts (run `pnpm gen:api`)
//
// The document must describe /x/v1: this app is pinned to that major version.

import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = fileURLToPath(new URL('..', import.meta.url));
const SPEC = join(root, 'openapi', 'openapi.v1.json');
const OUT = join(root, 'src', 'lib', 'kx', 'api-types.ts');

const BANNER = `// Generated by openapi-typescript from openapi/openapi.v1.json.
// Do not edit by hand: run \`pnpm gen:api\` after updating the OpenAPI document.

`;

async function assertPinnedToV1() {
  const spec = JSON.parse(await readFile(SPEC, 'utf8'));
  const servers = Array.isArray(spec.servers) ? spec.servers : [];
  const v1 = servers.length > 0 && servers.every((s) => typeof s?.url === 'string' && /\/x\/v1\/?$/.test(s.url));
  const version = String(spec.info?.version ?? '');
  if (!v1 || !version.startsWith('1.')) {
    throw new Error(
      `openapi/openapi.v1.json must describe /x/v1 (servers: ${servers.map((s) => s?.url).join(', ') || 'none'}, info.version: ${version || 'none'}).`,
    );
  }
}

async function generate() {
  // defaultNonNullable: false keeps request fields that have a default (e.g.
  // retry_next_best_source, freeze_protection) optional, as the API treats them.
  const ast = await openapiTS(pathToFileURL(SPEC), { defaultNonNullable: false });
  return BANNER + astToString(ast);
}

function firstDifference(a, b) {
  const left = a.split('\n');
  const right = b.split('\n');
  const n = Math.max(left.length, right.length);
  for (let i = 0; i < n; i++) {
    if (left[i] !== right[i]) {
      return `line ${i + 1}:\n  committed: ${left[i] ?? '(end of file)'}\n  expected:  ${right[i] ?? '(end of file)'}`;
    }
  }
  return null;
}

async function main() {
  const check = process.argv.includes('--check');
  await assertPinnedToV1();
  const generated = await generate();

  if (!check) {
    await writeFile(OUT, generated);
    console.log(`Wrote ${OUT.slice(root.length)}`);
    return;
  }

  const dir = await mkdtemp(join(tmpdir(), 'kx-api-types-'));
  try {
    const tmp = join(dir, 'api-types.ts');
    await writeFile(tmp, generated);
    const expected = await readFile(tmp, 'utf8');
    let committed = '';
    try {
      committed = await readFile(OUT, 'utf8');
    } catch {
      committed = '';
    }
    if (committed !== expected) {
      console.error('src/lib/kx/api-types.ts is out of date with openapi/openapi.v1.json.');
      const diff = firstDifference(committed, expected);
      if (diff) console.error(`First difference at ${diff}`);
      console.error('Run `pnpm gen:api` and commit the result.');
      process.exitCode = 1;
      return;
    }
    console.log('API types are up to date with openapi/openapi.v1.json.');
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
